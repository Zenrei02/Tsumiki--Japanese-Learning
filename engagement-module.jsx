/** Tappable token. The whole point: the learner checks the Japanese themselves. */
function Token({ tok, open, onToggle }) {
  const interactive = Boolean(tok.g);
  if (!interactive) return <span className="text-stone-500">{tok.t}</span>;
  return (
    <button
      onClick={onToggle}
      className={`relative rounded px-0.5 transition-colors ${
        open ? "bg-amber-100 text-stone-900" : "text-stone-800 hover:bg-stone-100"
      }`}
      style={{ textUnderlineOffset: 6 }}
    >
      {tok.r ? (
        <ruby>{tok.t}<rt className="text-[0.45em] font-normal text-stone-400">{tok.r}</rt></ruby>
      ) : tok.t}
    </button>
  );
}

function QuoteCard({ quote }) {
  const [openIdx, setOpenIdx] = useState(null);
  useEffect(() => setOpenIdx(null), [quote?.id]);
  if (!quote) return null;
  const open = openIdx == null ? null : quote.tokens[openIdx];

  return (
    <div className="rounded-xl border border-stone-200 bg-gradient-to-b from-amber-50/40 to-white p-5">
      <p className="mb-3 text-[11px] uppercase tracking-widest text-stone-400">Today</p>

      <div className="text-2xl leading-loose" lang="ja">
        {quote.tokens.map((t, i) => (
          <Token key={i} tok={t} open={openIdx === i}
            onToggle={() => setOpenIdx(openIdx === i ? null : i)} />
        ))}
      </div>

      {open ? (
        <div className="mt-3 rounded-lg border border-amber-200 bg-amber-50 p-3">
          <p className="text-sm font-medium text-stone-800">
            {open.t}{open.r ? ` — ${open.r}` : ""}
          </p>
          <p className="mt-0.5 text-sm text-stone-600">{open.g}</p>
          {open.ledger && open.ledger !== open.g && (
            <p className="mt-1 text-xs text-stone-500">also in your words: “{open.ledger}”</p>
          )}
        </div>
      ) : (
        <p className="mt-3 text-xs text-stone-400">Tap any word for its reading.</p>
      )}

      <div className="my-4 h-px bg-stone-200" />

      {/* ⚠️ THE THREE LABELS ARE A SEQUENCE, NOT A LIST (Lloyd, Session 23).
          They walk from what the words certainly say, to what they might mean,
          to the learner's own reading — and the last step is the one the card
          exists for. The previous version put the invitation in 11px grey at
          the bottom, which is where a disclaimer goes, not a question. An
          invitation that looks like small print gets read as small print.

          This is also what keeps the card off the reviewer's desk: an
          invitation cannot be wrong the way an assertion can, so nothing here
          needs a native-speaker ruling. Do not "improve" these into a stated
          meaning — that would put every card in the review queue. */}
      <p className="text-xs uppercase tracking-wider text-stone-400">Literally</p>
      <p className="mt-1 text-sm italic text-stone-600">{quote.literal}</p>

      <p className="mt-4 text-xs uppercase tracking-wider text-stone-400">It might mean</p>
      <p className="mt-1 text-sm leading-relaxed text-stone-700">{quote.one_reading}</p>

      <p className="mt-4 rounded-lg bg-stone-100 px-3 py-2 text-sm text-stone-700">
        {quote.invite}
      </p>

      <p className="mt-4 text-sm leading-relaxed text-stone-800">
        But what do <span className="font-semibold italic">you</span> think it is
        trying to say?
      </p>
      <p className="mt-1 text-xs text-stone-500">
        There is no answer waiting behind this. Yours may be the better one.
      </p>
    </div>
  );
}

function WeeklyTarget({ weekDays, count }) {
  const met = count >= WEEKLY_TARGET;
  const R = 26, C = 2 * Math.PI * R;
  return (
    <div className="flex items-center gap-4 rounded-xl border border-stone-200 bg-white p-4">
      <div className="relative shrink-0">
        <svg width="64" height="64" viewBox="0 0 64 64" className="-rotate-90">
          <circle cx="32" cy="32" r={R} fill="none" stroke="#e7e5e4" strokeWidth="5" />
          <circle cx="32" cy="32" r={R} fill="none" stroke={met ? "#9a3412" : "#78716c"}
            strokeWidth="5" strokeLinecap="round" strokeDasharray={C}
            strokeDashoffset={C * (1 - Math.min(1, count / WEEKLY_TARGET))}
            className="transition-all duration-700" />
        </svg>
        <div className="absolute inset-0 flex items-center justify-center">
          <span className={`text-lg font-semibold ${met ? "text-orange-800" : "text-stone-700"}`}>{count}</span>
        </div>
      </div>
      <div className="min-w-0 flex-1">
        <p className="text-sm font-medium text-stone-800">
          {met ? "This week's rhythm is kept." : `${count} of ${WEEKLY_TARGET} days this week`}
        </p>
        <p className="mt-0.5 text-xs text-stone-500">
          {met ? "Anything further is yours to enjoy." : "Any three days. They don't need to be in a row."}
        </p>
        <div className="mt-2 flex gap-1.5">
          {weekDays.map((d) => (
            <div key={d.key} className="flex flex-col items-center gap-1">
              <div className={[
                "h-6 w-6 rounded-md border transition-colors",
                d.active ? "border-orange-800 bg-orange-800"
                  : d.isToday ? "border-dashed border-stone-400 bg-white"
                  : d.future ? "border-stone-200 bg-stone-50" : "border-stone-200 bg-stone-100",
              ].join(" ")} />
              <span className="text-[10px] text-stone-400">{weekdayLabel(d.key)}</span>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}

function QuestChain({ chain, today, onClaim, onClaimBonus, onSimulate, devTools }) {
  if (!chain) {
    return (
      <div className="rounded-xl border border-dashed border-stone-300 bg-stone-50 p-4 text-sm text-stone-500">
        No path yet — unlock a module to begin one.
      </div>
    );
  }
  const core = chain.tasks.filter((t) => !t.bonus);
  const bonus = chain.tasks.find((t) => t.bonus);
  const coreDone = core.every((t) => t.done >= t.target);
  const bonusDone = bonus && bonus.done >= bonus.target;
  const daysLeft = CHAIN_WINDOW_DAYS - daysBetween(chain.startedOn, today);

  const Row = ({ t }) => {
    const done = t.done >= t.target;
    return (
      <li className="flex items-center gap-3">
        <div className={[
          "flex h-5 w-5 shrink-0 items-center justify-center rounded-full border text-[11px]",
          done ? (t.bonus ? "border-amber-600 bg-amber-600 text-white" : "border-orange-800 bg-orange-800 text-white")
               : "border-stone-300 bg-white text-transparent",
        ].join(" ")}>✓</div>
        <span className={`flex-1 text-sm ${done ? "text-stone-400 line-through" : t.bonus ? "text-amber-800" : "text-stone-700"}`}>
          {t.label}{t.target > 1 ? ` (${t.done}/${t.target})` : ""}
        </span>
        {devTools && !done && (
          <button onClick={() => onSimulate(t.module, t.kind)}
            className="rounded border border-stone-200 px-2 py-0.5 text-[11px] text-stone-500 hover:bg-stone-50">mark</button>
        )}
      </li>
    );
  };

  return (
    <div className="rounded-xl border border-stone-200 bg-white p-4">
      <div className="mb-3 flex items-baseline justify-between gap-3">
        <h3 className="text-sm font-medium text-stone-800">A short path</h3>
        <span className="text-xs text-stone-400">
          {coreDone ? "Complete" : daysLeft > 1 ? `${daysLeft} days left` : "Last day"}
        </span>
      </div>

      <ul className="space-y-2">{core.map((t) => <Row key={t.taskId} t={t} />)}</ul>

      {coreDone && !chain.claimed && (
        <button onClick={onClaim}
          className="mt-4 w-full rounded-lg bg-orange-800 px-4 py-2 text-sm font-medium text-white transition-colors hover:bg-orange-900">
          Collect
        </button>
      )}

      {bonus && (
        <div className="mt-4 rounded-lg border border-amber-200 bg-amber-50 p-3">
          <p className="mb-2 text-[11px] font-medium uppercase tracking-wide text-amber-800">
            Finished early — one more if you want it
          </p>
          <ul><Row t={bonus} /></ul>
          {bonusDone && !chain.bonusClaimed && (
            <button onClick={onClaimBonus}
              className="mt-3 w-full rounded-lg bg-amber-600 px-4 py-2 text-sm font-medium text-white hover:bg-amber-700">
              Collect
            </button>
          )}
        </div>
      )}

      {chain.claimed && (!chain.bonus || chain.bonusClaimed) && (
        <p className="mt-3 rounded-lg bg-stone-50 px-3 py-2 text-xs text-stone-500">
          A new path begins tomorrow.
        </p>
      )}
    </div>
  );
}

